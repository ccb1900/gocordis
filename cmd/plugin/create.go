// procSourceTemplate is a standalone OS process speaking the proc backend's
// line-delimited JSON-RPC 2.0 protocol over stdin/stdout using only stdlib.
const procSourceTemplate = `// Code generated by plugin create (backend=proc). Customize the methods.
//
// This is a standalone process, not a Go-native component. The gocordis proc
// backend spawns the executable once per activation and calls it over JSON-RPC.
package main

import (
	"bufio"
	"encoding/json"
	"fmt"
	"os"
)

const (
	handshakeHeader = "GORIDIS-PROC-PLUGIN 1"
	methodShutdown  = "shutdown"
)

type rpcRequest struct {
	JSONRPC string
	ID      *int
	Method  string
	Params  json.RawMessage
}

func main() {
	if err := serve(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func serve() error {
	out := bufio.NewWriter(os.Stdout)
	enc := json.NewEncoder(out)
	if _, err := fmt.Fprintln(out, handshakeHeader); err != nil {
		return err
	}
	if err := out.Flush(); err != nil {
		return err
	}

	in := bufio.NewScanner(os.Stdin)
	for in.Scan() {
		line := in.Bytes()
		if len(line) == 0 {
			continue
		}
		var req rpcRequest
		if err := json.Unmarshal(line, &req); err != nil {
			if err := writeError(enc, out, -32700, "parse error"); err != nil {
				return err
			}
			continue
		}
		if req.Method == methodShutdown {
			_ = writeResult(enc, out, req.ID, struct{}{})
			return nil // reply, then exit; the host force-kills after its timeout
		}
		result, err := dispatch(req.Method, req.Params)
		if err != nil {
			if err := writeError(enc, out, -32000, err.Error()); err != nil {
				return err
			}
			continue
		}
		if err := writeResult(enc, out, req.ID, result); err != nil {
			return err
		}
	}
	return in.Err()
}

// dispatch maps JSON-RPC method names (the plugin's commands/queries) to work.
// Rename or extend these names so they match the host's proc.NewBackend bind.
func dispatch(method string, params json.RawMessage) (any, error) {
	switch method {
	case "echo":
		var p struct{ Value string }
		if err := json.Unmarshal(params, &p); err != nil {
			return nil, err
		}
		return map[string]any{"value": p.Value}, nil
	default:
		return nil, fmt.Errorf("unknown method %q", method)
	}
}

func writeResult(enc *json.Encoder, out *bufio.Writer, id *int, result any) error {
	v := 0
	if id != nil {
		v = *id
	}
	if err := enc.Encode(map[string]any{"jsonrpc": "2.0", "id": v, "result": result}); err != nil {
		return err
	}
	return out.Flush()
}

func writeError(enc *json.Encoder, out *bufio.Writer, code int, message string) error {
	if err := enc.Encode(map[string]any{"jsonrpc": "2.0", "id": 0, "error": map[string]any{"code": code, "message": message}}); err != nil {
		return err
	}
	return out.Flush()
}
`

const procReadmeTemplate = `# {{.Name}}

Scaffolded by ` + "`plugin create`" + ` (id: {{.ID}}, backend: proc).

This is a standalone process project: it builds an executable, **not** a Go
` + "`runtime.Component`" + `. The gocordis proc backend spawns one fresh process per
component activation and links it as a remote provider, so there is no
` + "`component.go`" + ` here.

Files:

- ` + "`main.go`" + ` — stdlib JSON-RPC server over stdin/stdout.
- ` + "`go.mod`" + ` — standalone executable module (no gocordis dependency).
- ` + "`plugin.toml`" + ` — descriptive pluginmeta manifest.

## Process contract expected by the proc backend (v1)

1. On startup write the one-line handshake ` + "`GORIDIS-PROC-PLUGIN 1`" + ` to stdout and
   flush it. The host waits up to 5s for this line before declaring the
   activation failed.
2. Then serve line-delimited JSON-RPC 2.0 on stdin/stdout: requests look like
   ` + "`{\"jsonrpc\":\"2.0\",\"id\":1,\"method\":\"echo\",\"params\":{...}}`" + `; reply with one line
   ` + "`{\"jsonrpc\":\"2.0\",\"id\":1,\"result\":{...}}`" + ` (or an ` + "`error`" + ` object) and flush
   immediately. stderr is diagnostics only and is not part of the protocol.
3. Method names are the plugin's queries/commands. The host binds a typed
   capability to them via ` + "`proc.NewBackend(key, bind)`" + `, so the method names here
   must match that bind. The scaffold implements ` + "`echo`" + ` as a starting point.
4. On method ` + "`shutdown`" + `, reply then exit; the host sends this before killing
   after its shutdown timeout. Calls are sequential (one in-flight request),
   there is no automatic restart, and every call path returns an error.
5. A process boundary is not a security sandbox — the plugin runs with the
   host's privileges. For untrusted code use the WASM backend.

Build with ` + "`go build -o {{.ID}} .`" + ` and point ` + "`plugin.toml`" + ` source.location
(` + "`{{.Location}}`" + `) at the executable via
` + "`loader.Artifact{BackendType: loader.BackendProc, Source: ...}`" + `.

Run ` + "`plugin doctor plugin.toml`" + ` to validate metadata.
`

